#!/usr/bin/env python3
"""Build ptf_gator_data.pbo, the G/ATOR's model and textures, from the purchased model.

The art is a paid CGTrader model ("AN-TPS-80 Ground Air Radar System Deployed" by 3dmi),
licensed for use in the mod but not for redistribution as source. This repo is public, so
none of it is committed: this script reads the artist's files from a folder outside git and
builds a binarized PBO that ships with the mod like the other external PBOs
(PTF_EXTERNAL_ADDONS). The config and scripts that use it are in addons/PTF_GATOR.

Usage:
    python tools/gator/build_data.py [--source <folder>] [--install] [--renders]

--source   the folder the purchase was downloaded to (default: $PTF_GATOR_SOURCE). The .rar
           archives are unpacked into <source>/extracted the first time.
--install  copy the PBO into $PTF_EXTERNAL_ADDONS as well.
--renders  also write Blender renders of the stow sequence to <source>/arma/review.

Needs Blender 5.x, Arma 3 Tools (ImageToPAA, Binarize), HEMTT, Pillow and numpy.
Output: <source>/arma/ptf_gator_data.pbo
"""
import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BLENDER = Path(r"C:\Program Files\Blender Foundation\Blender 5.1\blender.exe")
TAR = Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "tar.exe"
STEM = "AN-TPS-80_Ground_Air_Radar_System_Deployed"

PROJECT_TOML = """# Generated by tools/gator/build_data.py
name = "PTF G/ATOR data"
prefix = "ptf_gator"
mainprefix = "z"
author = "Paramarine Task Force"

[version]
major = 1
minor = 0
patch = 0
build = 0
git_hash = 0
"""

DATA_CONFIG = """// Generated by tools/gator/build_data.py - do not hand-edit.
// Model and textures for PTF_GATOR. Built outside git from a purchased model; see
// tools/gator/README.md in the PTF Core repo.
class CfgPatches
{
    class ptf_gator_data
    {
        name = "PTF Core - G/ATOR model";
        units[] = {};
        weapons[] = {};
        requiredVersion = 2.18;
        requiredAddons[] = {"A3_Data_F"};
        author = "Paramarine Task Force (model: 3dmi, CGTrader)";
    };
};
"""


def extract(source):
    out = source / "extracted"
    for part in ("blender_base", "textures"):
        target = out / part
        if target.is_dir() and any(target.iterdir()):
            continue
        target.mkdir(parents=True, exist_ok=True)
        archive = source / f"{STEM}_{part}.rar"
        print(f"Unpacking {archive.name}")
        subprocess.run([str(TAR), "-xf", str(archive), "-C", str(target)], check=True)
    blend = next((out / "blender_base").glob("*.blend"))
    return blend, out / "textures"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", default=os.environ.get("PTF_GATOR_SOURCE"))
    ap.add_argument("--install", action="store_true")
    ap.add_argument("--renders", action="store_true")
    args = ap.parse_args()
    if not args.source or not Path(args.source).is_dir():
        sys.exit("Pass --source or set PTF_GATOR_SOURCE to the folder with the purchased model's archives.")
    source = Path(args.source)
    blend, textures = extract(source)

    work = source / "arma"
    project = work / "project"
    addon = project / "addons" / "data"
    shutil.rmtree(project, ignore_errors=True)
    (addon / "data").mkdir(parents=True)
    (project / ".hemtt").mkdir(parents=True)
    (project / ".hemtt" / "project.toml").write_text(PROJECT_TOML, newline="\n")
    (addon / "$PBOPREFIX$").write_text("z\\ptf_gator\\addons\\data", newline="\n")
    (addon / "config.cpp").write_text(DATA_CONFIG, newline="\n")

    cmd = [str(BLENDER), "-b", str(blend), "--python", str(HERE / "build_model.py"), "--", str(addon)]
    if args.renders:
        cmd += ["--renders", str(work / "review")]
    print("Building the model in Blender")
    run = subprocess.run(cmd, capture_output=True, text=True)
    report = [line for line in run.stdout.splitlines() if line.split(" ")[0] in
              ("PIECES", "LOD", "COLLISION", "MASS", "OVERLAP_NEW", "DONE", "Traceback") or "Error" in line]
    print("\n".join("  " + line for line in report))
    if "DONE" not in run.stdout:
        print(run.stdout[-4000:], run.stderr[-2000:])
        sys.exit("Blender build failed")
    # The model's notes (expected probe positions) are for the in-game test, not the PBO.
    shutil.move(str(addon / "gator_model.json"), str(work / "gator_model.json"))

    print("Converting textures")
    subprocess.run([sys.executable, str(HERE / "build_textures.py"), str(textures), str(addon / "data")], check=True)

    print("Packing with HEMTT (binarizes the model)")
    subprocess.run(["hemtt", "build"], cwd=project, check=True)
    pbo = project / ".hemttout" / "build" / "addons" / "ptf_gator_data.pbo"
    shutil.copy2(pbo, work / pbo.name)
    print(f"Built {work / pbo.name} ({(work / pbo.name).stat().st_size / 1e6:.1f} MB)")
    if args.install:
        ext = os.environ.get("PTF_EXTERNAL_ADDONS")
        if not ext or not Path(ext).is_dir():
            sys.exit("--install needs PTF_EXTERNAL_ADDONS")
        shutil.copy2(pbo, Path(ext) / pbo.name)
        print(f"Installed into {ext}")


if __name__ == "__main__":
    main()

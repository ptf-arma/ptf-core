def load(path, size, mode="RGB"):
    im = Image.open(path).convert(mode)
    return im.resize((size, size), Image.LANCZOS) if im.size != (size, size) else im


def to_paa(img, target, tmp):
    png = Path(tmp) / (target.stem + ".png")
    img.save(png)
    subprocess.run([str(IMAGE_TO_PAA), str(png), str(target)], check=True, capture_output=True)
    print(f"  {target.name}")


def weathered(alpha, rng, strength):
    """Wear a mask: blotchy fading plus fine speckle, like stencilled paint gone dull."""
    h, w = alpha.shape
    blotch = np.asarray(Image.fromarray((rng.random((h // 32, w // 32)) * 255).astype(np.uint8)).resize((w, h), Image.BICUBIC), np.float32) / 255
    speck = rng.random((h, w))
    keep = np.clip(1.0 - strength * (blotch * 0.8 + (speck > 0.93) * 0.6), 0, 1)
    return alpha * keep


def build_markings(out, tmp):
    """'PROPERTY OF THE PARAMARINE TASK FORCE' in stencil-style capitals, and a faded PTF
    patch, as one _ca sheet with alpha."""
    rng = np.random.default_rng(7)
    w, h = DECAL_SIZE
    rgba = np.zeros((h, w, 4), np.float32)

    text = Image.new("L", (w, 480), 0)
    d = ImageDraw.Draw(text)
    for line, size, y in (("PROPERTY OF THE", 150, 20), ("PARAMARINE TASK FORCE", 220, 210)):
        font = ImageFont.truetype(FONT, size)
        x0, y0, x1, y1 = d.textbbox((0, 0), line, font=font)
        d.text(((w - (x1 - x0)) / 2 - x0, y), line, fill=255, font=font)
    # Stencil bridges: thin uncut gaps through the letters every so often, as a stencil leaves.
    a = np.asarray(text, np.float32) / 255
    for col in range(37, w, 74):
        a[:, col:col + 7] *= 0.0
    a = np.asarray(Image.fromarray((a * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2)), np.float32) / 255
    a = weathered(a, rng, 0.55) * 0.88
    rgba[:480, :, :3] = np.array([26, 28, 22]) / 255
    rgba[:480, :, 3] = a

    png = Path(tmp) / "emblem.png"
    subprocess.run([str(IMAGE_TO_PAA), str(EMBLEM), str(png)], check=True, capture_output=True)
    emblem = Image.open(png).convert("RGBA")
    emblem = emblem.crop(emblem.getbbox()).resize((464, 496), Image.LANCZOS)
    e = np.asarray(emblem, np.float32) / 255
    grey = e[..., :3].mean(2, keepdims=True)
    colour = e[..., :3] * 0.45 + grey * 0.55          # half the saturation
    colour = colour * 0.8 + np.array([0.33, 0.35, 0.27]) * 0.2   # sun-faded towards olive
    alpha = weathered(e[..., 3], rng, 0.7) * 0.55
    rgba[520:1016, 8:472, :3] = colour
    rgba[520:1016, 8:472, 3] = alpha

    to_paa(Image.fromarray((np.clip(rgba, 0, 1) * 255).astype(np.uint8), "RGBA"), out / "markings_ca.paa", tmp)


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        for name, (stem, normal, size, smdi_size) in SETS.items():
            to_paa(load(src / f"{stem}_BaseColor.png", size), out / f"{name}_co.paa", tmp)
            to_paa(load(src / normal, size), out / f"{name}_nohq.paa", tmp)
            rough = np.asarray(load(src / f"{stem}_Roughness.png", smdi_size, "L"), np.float32) / 255
            metal = np.asarray(load(src / f"{stem}_Metallic.png", smdi_size, "L"), np.float32) / 255
            gloss = 1.0 - rough
            smdi = np.zeros((smdi_size, smdi_size, 3), np.uint8)
            smdi[..., 0] = 255
            # Painted military kit: modest highlights, brighter on bare metal.
            smdi[..., 1] = np.clip((0.15 + 0.55 * gloss + 0.3 * metal) * 255, 0, 255)
            smdi[..., 2] = np.clip(gloss * 255, 0, 255)
            to_paa(Image.fromarray(smdi, "RGB"), out / f"{name}_smdi.paa", tmp)
            (out / f"{name}.rvmat").write_text(rvmat(name), newline="\n")
            (out / f"{name}_destruct.rvmat").write_text(burnt(rvmat(name)), newline="\n")
        build_markings(out, tmp)
    # The light lenses: the trailer's texture, dimmed and glassy, so the lights read as off.
    lights = rvmat("support").replace("ambient[] = {1,1,1,1};", "ambient[] = {0.35,0.35,0.35,1};")
    lights = lights.replace("diffuse[] = {1,1,1,1};", "diffuse[] = {0.35,0.35,0.35,1};").replace("specularPower = 60;", "specularPower = 150;")
    (out / "lights.rvmat").write_text(lights, newline="\n")
    # Lit, while towed behind a vehicle with its lights on: the lens texture glowing.
    lit = rvmat("support").replace("emmisive[] = {0,0,0,1};", "emmisive[] = {40,40,40,1};")
    (out / "lights_on.rvmat").write_text(lit, newline="\n")


if __name__ == "__main__":
    main()
